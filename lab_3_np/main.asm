.386
.MODEL FLAT

.CODE
_SUBSTR PROC				; имя с нижним подчеркиванием соответствует глобальному идентификатору, 
							; определенному в программе
	PUSH EBP				; сохраняем значение EBP, т.к. подпрограмма не должна его изменять. 
							; используем его как указатель базы стека
	MOV EBP, ESP			; в ESP лежит адрес возврата в программу
	MOV ESI, [EBP + 8]		; в стеке по этому адресу лежит адрес первого символа строки SOURCE
	MOV EAX, [EBP + 12]		; POS
	ADD ESI, EAX			; теперь ESI указывает на первый символ подстроки
	MOV EDI, [EBP + 20]		; тут адрес буфера DEST
	MOV ECX, [EBP + 16]		; тут длина LEN
	CLD

L:
	LODSB					; загрузит текущий элемент цепочки по адресу из ESI в регистр AL,
							; т.к. работаем с байтами
	CMP AL, 'a'				; проверка, что символ в диапазоне от 'a' до 'z'
	JB STORE
	CMP AL, 'z'
	JA STORE				; если в диапазоне, то переходим на метку STORE
	AND AL, 11011111B		; если нет, то с помощью логического побитового умножения и маски
							; 11011111 обнуляем пятый разряд символа из AL
STORE:
	STOSB					; сохранит элемент цепочки из AL по адресу из EDI, а там у нас буфер
	LOOP L
	MOV BYTE PTR [EDI], 0
	POP EBP					; восстанавливаем значение EBP
	RET						; нет аргументов у RET, так как стек, по соглашению cdecl, очищает программа,
							; а не подпрограмма
_SUBSTR ENDP
END
	